from __future__ import annotations

from deckgen.contracts import (DeckPlan, Evidence, IngestResult, SlideSpec, SlideType, SourceSection, SourceTable,
                               TableSpec)

T1 = SourceTable(
    table_id="t1", caption="Ключевые показатели генерации",
    columns=["Показатель", "Ед. изм.", "2022", "2023", "2024", "Изм., %"],
    rows=[
        ["Установленная мощность", "МВт", "5 120", "5 120", "5 310", "3,7"],
        ["Выработка электроэнергии", "млрд кВт·ч", "18,4", "18,6", "19,1", "2,7"],
        ["Отпуск тепла", "тыс. Гкал", "9 870", "10 020", "9 940", "−0,8"],
        ["КИУМ", "%", "41,0", "41,5", "41,1", "—"],
        ["Удельный расход условного топлива", "г/кВт·ч", "312,4", "309,8", "306,2", "−1,2"],
        ["Аварийность", "ед.", "14", "11", "9", "−18,2"],
        ["Выручка", "млрд руб.", "142", "158", "171", "8,2"],
        ["EBITDA", "млрд руб.", "~23*", "27,4", "31,0", "13,1"],
        ["Инвестиции (CAPEX)", "млрд руб.", "18,9", "22,3", "25,0", "12,1"],
        ["Численность персонала", "чел.", "4 812", "4 760", "4 701", "−1,2"],
        ["Доля ВИЭ в выработке", "%", "≥ 10", "≥ 11", "≥ 12", "—"],
    ])

T2 = SourceTable(
    table_id="t2", caption="Объекты ремонтной программы 2025",
    columns=["№", "Объект", "Филиал", "Вид ремонта", "Мощность, МВт", "Начало", "Окончание", "Бюджет, млн руб."],
    rows=[[str(i), f"Энергоблок ст. №{i}", ["Северный", "Южный", "Центральный"][i % 3],
           ["капитальный", "средний", "текущий"][i % 3], f"{100 + i * 15}", f"{(i % 12) + 1:02d}.2025",
           f"{(i % 12) + 1:02d}.2025", f"{12 + i * 3},5"] for i in range(1, 31)])

TEXT = """# Итоги 2024 года
Выработка электроэнергии за 2024 год составила 19,1 млрд кВт·ч, что на 2,7% выше уровня 2023 года.
Установленная мощность выросла до 5 310 МВт после ввода новой ПГУ.
"""


def ingest() -> IngestResult:
    return IngestResult(raw_text=TEXT, source_hash="ml2-fixture",
                        sections=[SourceSection(section_id="s1", heading="Итоги 2024 года", text=TEXT,
                                                table_ids=["t1", "t2"])],
                        tables=[T1, T2])


def plan() -> DeckPlan:
    long_bullets = [f"Мероприятие {i}: модернизация оборудования и цифровизация процессов на объекте №{i} "
                    f"с целью снижения удельного расхода топлива и повышения надёжности" for i in range(1, 13)]
    return DeckPlan(deck_title="Итоги работы генерирующей компании за 2024 год", slides=[
        SlideSpec(type=SlideType.title, title="Итоги работы генерирующей компании за 2024 год",
                  subtitle="Докладчик: И. И. Иванов, директор по производству\nМосква, 2025"),
        SlideSpec(type=SlideType.section, title="Производственные результаты"),
        SlideSpec(type=SlideType.slide, title="Главное за год",
                  bullets=["Выработка электроэнергии — 19,1 млрд кВт·ч (+2,7% к 2023 году)",
                           "Установленная мощность увеличена до 5 310 МВт после ввода ПГУ",
                           "Аварийность снижена на 18,2%: 9 событий против 11 годом ранее",
                           "Удельный расход условного топлива — 306,2 г/кВт·ч"],
                  notes="Акцент на росте выработки и снижении аварийности.",
                  evidence=[Evidence(quote="составила 19,1 млрд кВт·ч")]),
        SlideSpec(type=SlideType.table, title="Ключевые показатели 2022–2024",
                  bullets=["Рост выработки при снижении удельного расхода топлива",
                           "EBITDA выросла на 13,1%"],
                  table=TableSpec(source_id="t1")),
        SlideSpec(type=SlideType.table, title="Ключевые показатели (таблица целиком)", table=TableSpec(source_id="t1")),
        SlideSpec(type=SlideType.slide, title="Программа повышения эффективности", bullets=long_bullets),
        SlideSpec(type=SlideType.table, title="Ремонтная программа 2025", table=TableSpec(source_id="t2")),
        SlideSpec(type=SlideType.slide, title="Пустой слайд превращается в раздел"),
        SlideSpec(type=SlideType.last, title="Спасибо за внимание!"),
    ])
